import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const output=path.resolve(process.env.EDITOR_OUTPUT??'/tmp/slide-fable-common-evidence');
await mkdir(output,{recursive:true});
const server=spawn('node',['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5197','--strictPort'],{stdio:['ignore','pipe','pipe']});
let browser;const checks=[];
const pass=name=>{checks.push({name,result:'PASS'});console.log('PASS',name);};
try{
 await new Promise((resolve,reject)=>{let log='';const timer=setTimeout(()=>reject(Error('Vite startup: '+log)),20000);server.stdout.on('data',d=>{log+=d;if(log.includes('5197')){clearTimeout(timer);resolve();}});server.on('exit',code=>{clearTimeout(timer);reject(Error('Vite exited '+code));});});
 browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE,args:['--no-sandbox','--disable-dev-shm-usage']}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5197/');
 await page.getByRole('button',{name:'Lägg till bild',exact:true}).waitFor();
 const model=()=>page.evaluate(async()=>(await import('/src/core/editor.ts')).editorStore.getSnapshot().doc);
 const before=await model();
 await page.getByRole('tab',{name:'Design',exact:true}).click();
 await page.getByRole('button',{name:'Layout och tema',exact:true}).click();
 const gallery=page.getByRole('region',{name:'Layout- och temagalleri'});
 assert.equal(await gallery.getByRole('group',{name:'Layoutgalleri'}).getByRole('button').count(),5);
 await gallery.getByRole('button',{name:'Använd layout Två kolumner',exact:true}).click();
 assert.equal((await model()).slides[0].placeholderBindings.length,3);
 await gallery.getByRole('button',{name:'Använd tema Midnatt',exact:true}).click();
 assert.equal((await model()).theme.colors.surface,'#173944');
 assert.equal(await gallery.getByRole('button',{name:'Använd tema Midnatt',exact:true}).getAttribute('aria-pressed'),'true');
 const actualBackground=await page.locator('.stage .slide-render').evaluate(el=>getComputedStyle(el).backgroundColor);
 assert.equal(actualBackground,'rgb(23, 57, 68)');
 await gallery.getByLabel('Accentfärg i temat',{exact:true}).fill('#4499aa');
 await gallery.getByLabel('Rubriktypsnitt',{exact:true}).selectOption('Verdana');
 assert.equal((await model()).theme.styles.heading.fontFamily,'Verdana');
 await page.screenshot({path:path.join(output,'design-gallery-desktop.png'),fullPage:true});
 const source=await model();
 const pendingDownload=page.waitForEvent('download');
 await gallery.getByRole('button',{name:'Spara designmall',exact:true}).click();
 const download=await pendingDownload,template=JSON.parse(await readFile(await download.path(),'utf8'));
 assert.equal(template.theme.colors.accent,'#4499aa');assert.equal(template.theme.styles.heading.fontFamily,'Verdana');
 assert.equal(template.slides.length,1);assert.notEqual(template.document.id,source.document.id);
 assert.deepEqual(await model(),source,'Saving a design template must not change the presentation');
 await page.evaluate(async template=>{await (await import('/src/core/contract.ts')).validateFull(template);},template);
 await page.setViewportSize({width:768,height:1024});
 await page.screenshot({path:path.join(output,'design-gallery-tablet.png'),fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
 await page.setViewportSize({width:1440,height:1000});
 await page.evaluate(async before=>(await import('/src/core/editor.ts')).editorStore.load(before),before);
 pass('COMMON-03:layout-theme-customization-template-download-and-tablet');
 assert.deepEqual(errors,[]);
}finally{
 await writeFile(path.join(output,'common-workflows-results.json'),JSON.stringify({checks,engine:browser?.version()},null,2));
 if(browser)await browser.close();server.kill();
}
